using Netrunner.Cards;
using Netrunner.Core;
using Xunit;

namespace Netrunner.Match.Tests;

/// <summary>
/// Keeps trigger automation reviewed as cards are added. Every effect kind must be
/// classified, and every card trigger's verdict is compared against a reviewed list
/// (Fixtures/trigger-automation-audit.txt). A new card, trigger or effect kind fails
/// here until someone reads its verdict and accepts it.
/// </summary>
public sealed class TriggerAutomationAuditTests
{
    private static string FixturePath => Path.GetFullPath(Path.Combine(AppContext.BaseDirectory,
        "..", "..", "..", "Fixtures", "trigger-automation-audit.txt"));

    [Fact]
    public void EveryEffectKindIsClassified()
    {
        BehaviorInstructionKind[] missing = [.. Enum.GetValues<BehaviorInstructionKind>().Distinct()
            .Where(kind => !BeneficialTriggers.Verdicts.ContainsKey(kind))];
        Assert.True(missing.Length == 0,
            $"Classify {string.Join(", ", missing)} in BeneficialTriggers.Verdicts: is it always a gain, a gain only in some situations, or the player's decision?");
    }

    [Fact]
    public void EveryCardTriggerHasAReviewedVerdict()
    {
        string[] actual = [.. GatewayBehaviorCatalog.Create().GenericSpecs
            .SelectMany(card => card.Triggers.Select(trigger => BeneficialTriggers.Describe(card, trigger)))
            .Order(StringComparer.Ordinal)];
        string[] reviewed = File.Exists(FixturePath)
            ? [.. File.ReadAllLines(FixturePath).Where(line => line.Length > 0 && !line.StartsWith('#'))]
            : [];
        string[] added = [.. actual.Except(reviewed, StringComparer.Ordinal)];
        string[] removed = [.. reviewed.Except(actual, StringComparer.Ordinal)];
        if (added.Length == 0 && removed.Length == 0) return;
        File.WriteAllLines(FixturePath + ".actual", [.. Header, .. actual]);
        Assert.Fail("Trigger automation changed. Review each line, then replace the fixture with "
            + $"{FixturePath}.actual.\nNew or changed:\n  {string.Join("\n  ", added)}\nNo longer produced:\n  {string.Join("\n  ", removed)}");
    }

    private static readonly string[] Header =
    [
        "# Trigger automation audit: when the client resolves each card trigger for the player.",
        "# Generated by TriggerAutomationAuditTests from BeneficialTriggers; review every change.",
        "# \"automatic\" resolves (or orders) on its own; \"player decides\" always asks.",
        "",
    ];
}
