#!/usr/bin/env python3
"""Authenticate local card metadata and emit a deterministic C# payload.

The official source snapshot is deliberately ignored by Git.  This helper is
invoked by Netrunner.Cards' MSBuild target; it never downloads anything.  A
synthetic fixture is used only when content is not explicitly requested and
the local official snapshot is absent.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import pathlib
import sys


OFFICIAL_COMMIT = "236140cf84491c23995b028bc791281837520b97"
OFFICIAL_SOURCE = "https://github.com/Null-Signal-Games/netrunner-cards-json"


def fail(message: str) -> "NoReturn":
    raise SystemExit(f"DATA-400: {message}")


def read_bytes(path: pathlib.Path, description: str) -> bytes:
    try:
        return path.read_bytes()
    except FileNotFoundError:
        fail(
            f"{description} is missing at '{path}'. "
            "Run ./scripts/update-card-data.sh --commit "
            f"{OFFICIAL_COMMIT} --retrieval-date 2026-08-28."
        )
    except OSError as error:
        fail(f"unable to read {description} at '{path}': {error}")


def parse_json(raw: bytes, path: pathlib.Path, description: str):
    try:
        return json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        fail(f"{description} at '{path}' is corrupt: {error}")


def validate_payload(
    cards_raw: bytes,
    manifest_raw: bytes,
    copyright_raw: bytes,
    cards_path: pathlib.Path,
    manifest_path: pathlib.Path,
    copyright_path: pathlib.Path,
    official: bool,
) -> None:
    cards = parse_json(cards_raw, cards_path, "normalized card data")
    manifest = parse_json(manifest_raw, manifest_path, "card-data manifest")
    if not isinstance(cards, list) or not cards:
        fail(f"normalized card data at '{cards_path}' must be a non-empty array")
    if not isinstance(manifest, dict):
        fail(f"card-data manifest at '{manifest_path}' must be an object")
    expected_hash = manifest.get("outputSha256")
    actual_hash = hashlib.sha256(cards_raw).hexdigest()
    if expected_hash != actual_hash:
        fail(
            f"normalized checksum mismatch for '{cards_path}': manifest has "
            f"'{expected_hash}', actual bytes have '{actual_hash}'"
        )
    if manifest.get("cardCount") != len(cards):
        fail(
            f"manifest cardCount {manifest.get('cardCount')!r} does not match "
            f"normalized data count {len(cards)}"
        )
    if not isinstance(copyright_raw, bytes) or not copyright_raw:
        fail(f"source copyright notice at '{copyright_path}' must not be empty")
    try:
        copyright_raw.decode("utf-8")
    except UnicodeDecodeError as error:
        fail(f"source copyright notice at '{copyright_path}' is not valid UTF-8: {error}")

    if official:
        required = {
            "sourceUrl": OFFICIAL_SOURCE,
            "commitSha": OFFICIAL_COMMIT,
            "sourcePackPath": "pack/sg.json",
            "sourceLicensePath": "COPYRIGHT.md",
            "upstreamSchemaVersion": "v1",
            "packCode": "sg",
            "cardCount": 77,
        }
        for field, expected in required.items():
            if manifest.get(field) != expected:
                fail(
                    f"stale or incompatible official manifest field {field!r}: "
                    f"found {manifest.get(field)!r}, expected {expected!r}"
                )
        if len(cards) != 77:
            fail(f"official System Gateway metadata must contain 77 records, found {len(cards)}")
    else:
        if manifest.get("packCode") != "m4-synthetic":
            fail("synthetic fixture has an unexpected packCode")


def csharp_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def emit(output: pathlib.Path, mode: str, cards: bytes, manifest: bytes, copyright_notice: bytes) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    encoded = {
        "Cards": base64.b64encode(cards).decode("ascii"),
        "Manifest": base64.b64encode(manifest).decode("ascii"),
        "Copyright": base64.b64encode(copyright_notice).decode("ascii"),
    }
    content = """// <auto-generated /> DATA-400 authenticated card-data payload.
namespace Netrunner.Cards;

internal static class GeneratedCardData
{{
    internal const string Mode = \"{mode}\";
    internal const string CardsBase64 = \"{cards}\";
    internal const string ManifestBase64 = \"{manifest}\";
    internal const string CopyrightBase64 = \"{copyright}\";
}}
""".format(
        mode=csharp_string(mode),
        cards=encoded["Cards"],
        manifest=encoded["Manifest"],
        copyright=encoded["Copyright"],
    )
    try:
        if output.exists() and output.read_text(encoding="utf-8") == content:
            return
        output.write_text(content, encoding="utf-8", newline="\n")
    except OSError as error:
        fail(f"unable to write generated resource '{output}': {error}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("official", "synthetic"), required=True)
    parser.add_argument("--input-root", type=pathlib.Path, required=True)
    parser.add_argument("--synthetic-root", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()

    root = args.input_root if args.mode == "official" else args.synthetic_root
    cards_path = root / "cards.json"
    manifest_path = root / "manifest.json"
    copyright_path = root / ("SOURCE_COPYRIGHT.md" if args.mode == "official" else "SYNTHETIC.md")
    cards = read_bytes(cards_path, "normalized card data")
    manifest = read_bytes(manifest_path, "card-data manifest")
    copyright_notice = read_bytes(copyright_path, "source copyright notice")
    validate_payload(
        cards,
        manifest,
        copyright_notice,
        cards_path,
        manifest_path,
        copyright_path,
        args.mode == "official",
    )
    emit(args.output, args.mode, cards, manifest, copyright_notice)
    return 0


if __name__ == "__main__":
    sys.exit(main())
